%% EXPERIMENTO 3: SOLUCIÓN SUAVE Y ESTUDIO DE CONVERGENCIA
%
% Ecuación de Burgers:
%
%       u_t + (u^2/2)_x = 0
%
% Condición inicial periódica:
%
%       u(x,0) = 0.5 + 0.25*sin(pi*x)
%
% El tiempo de formación del shock es:
%
%       t_s = 4/pi ~= 1.273
%
% Se utiliza tFinal = 0.5, de modo que la solución permanece suave.

clear;
clc;
close all;

%% Parámetros generales

xmin = -1;
xmax = 1;

tFinal = 0.5;
CFL = 0.6;

caseName = "smooth";
boundaryName = "periodic";

limiters = [
    "minmod"
    "vanleer"
    "vanalbada"
    "superbee"
];

numberOfLimiters = numel(limiters);

shockFormationTime = 4/pi;

fprintf('\n====================================================\n');
fprintf('EXPERIMENTO DE SOLUCIÓN SUAVE\n');
fprintf('====================================================\n');
fprintf('Tiempo final                = %.4f\n', tFinal);
fprintf('Tiempo de formación shock   = %.4f\n', ...
    shockFormationTime);
fprintf('Condición de contorno       = %s\n\n', ...
    boundaryName);

%% ============================================================
%  PARTE A: COMPARACIÓN PARA UNA MALLA FIJA
% =============================================================

N = 200;
dx = (xmax - xmin)/N;

%% Godunov

[x, uGodunov, ~, diagnosticGodunov] = ...
    solve_burgers_godunov( ...
        N, xmin, xmax, tFinal, CFL, ...
        caseName, boundaryName);

%% Solución exacta

uExact = exact_burgers_solution(x, tFinal, caseName);
uInitial = initial_condition(x, caseName);

%% MUSCL con todos los limitadores

solutions = zeros(N, numberOfLimiters);

errorL1 = zeros(numberOfLimiters,1);
errorLinf = zeros(numberOfLimiters,1);
finalTV = zeros(numberOfLimiters,1);
massResidual = zeros(numberOfLimiters,1);

diagnostics = cell(numberOfLimiters,1);

for k = 1:numberOfLimiters

    [~, uMUSCL, ~, diagnostic] = ...
        solve_burgers_muscl( ...
            N, xmin, xmax, tFinal, CFL, ...
            caseName, limiters(k), boundaryName);

    solutions(:,k) = uMUSCL;
    diagnostics{k} = diagnostic;

    errorL1(k) = ...
        dx*sum(abs(uMUSCL - uExact));

    errorLinf(k) = ...
        max(abs(uMUSCL - uExact));

    finalTV(k) = diagnostic.TV(end);

    massResidual(k) = max(abs( ...
        diagnostic.mass ...
        - diagnostic.expectedMass));
end

%% Error de Godunov

errorGodunovL1 = ...
    dx*sum(abs(uGodunov - uExact));

errorGodunovLinf = ...
    max(abs(uGodunov - uExact));

%% Tabla de la malla fija

fixedGridTable = table( ...
    limiters, ...
    errorL1, ...
    errorLinf, ...
    finalTV, ...
    massResidual, ...
    'VariableNames', { ...
        'Limitador', ...
        'Error_L1', ...
        'Error_Linf', ...
        'TV_final', ...
        'Residuo_masa'});

fprintf('COMPARACIÓN PARA N = %d\n\n', N);

fprintf('Godunov:\n');
fprintf('  Error L1   = %.8e\n', errorGodunovL1);
fprintf('  Error Linf = %.8e\n\n', errorGodunovLinf);

disp(fixedGridTable);

%% Figura 1: solución

figure;

plot(x, uInitial, '--', ...
    'LineWidth', 1.2, ...
    'DisplayName', 'Condición inicial');

hold on;

plot(x, uExact, ...
    'LineWidth', 2.5, ...
    'DisplayName', 'Solución exacta');

plot(x, uGodunov, ...
    'LineWidth', 1.5, ...
    'DisplayName', 'Godunov');

for k = 1:numberOfLimiters

    plot(x, solutions(:,k), ...
        'LineWidth', 1.2, ...
        'DisplayName', ...
        sprintf('MUSCL-%s', limiters(k)));

end

grid on;
xlabel('x');
ylabel('u(x,t)');

title(sprintf( ...
    'Solución suave de Burgers, t = %.2f, N = %d', ...
    tFinal, N));

legend('Location', 'eastoutside');
xlim([xmin xmax]);

%% Figura 2: error absoluto

figure;

plot(x, abs(uGodunov-uExact), ...
    '--', ...
    'LineWidth', 1.5, ...
    'DisplayName', 'Godunov');

hold on;

for k = 1:numberOfLimiters

    plot(x, abs(solutions(:,k)-uExact), ...
        'LineWidth', 1.3, ...
        'DisplayName', ...
        sprintf('MUSCL-%s', limiters(k)));

end

grid on;
xlabel('x');
ylabel('|u_{num}-u_{exacta}|');
title('Distribución espacial del error');
legend('Location', 'eastoutside');

%% Figura 3: evolución de la variación total

figure;

plot( ...
    diagnosticGodunov.time, ...
    diagnosticGodunov.TV, ...
    '--', ...
    'LineWidth', 1.5, ...
    'DisplayName', 'Godunov');

hold on;

for k = 1:numberOfLimiters

    plot( ...
        diagnostics{k}.time, ...
        diagnostics{k}.TV, ...
        'LineWidth', 1.2, ...
        'DisplayName', ...
        sprintf('MUSCL-%s', limiters(k)));

end

grid on;
xlabel('Tiempo');
ylabel('TV(u)');
title('Variación total para la solución suave');
legend('Location', 'best');

%% ============================================================
%  PARTE B: ESTUDIO DE CONVERGENCIA
% =============================================================

Nvalues = [
    50
    100
    200
    400
    800
];

numberOfMeshes = numel(Nvalues);

dxValues = zeros(numberOfMeshes,1);

errorsGodunov = zeros(numberOfMeshes,1);
ordersGodunov = NaN(numberOfMeshes,1);

errorsMUSCL = zeros( ...
    numberOfMeshes, numberOfLimiters);

ordersMUSCL = NaN( ...
    numberOfMeshes, numberOfLimiters);

fprintf('\nREALIZANDO ESTUDIO DE CONVERGENCIA...\n');

for meshIndex = 1:numberOfMeshes

    currentN = Nvalues(meshIndex);
    currentDx = (xmax-xmin)/currentN;

    dxValues(meshIndex) = currentDx;

    %% Godunov

    [xCurrent, uCurrentGodunov] = ...
        solve_burgers_godunov( ...
            currentN, xmin, xmax, ...
            tFinal, CFL, caseName, boundaryName);

    exactCurrent = exact_burgers_solution( ...
        xCurrent, tFinal, caseName);

    errorsGodunov(meshIndex) = ...
        currentDx*sum(abs( ...
            uCurrentGodunov-exactCurrent));

    %% MUSCL

    for limiterIndex = 1:numberOfLimiters

        [~, uCurrentMUSCL] = ...
            solve_burgers_muscl( ...
                currentN, xmin, xmax, ...
                tFinal, CFL, caseName, ...
                limiters(limiterIndex), ...
                boundaryName);

        errorsMUSCL(meshIndex,limiterIndex) = ...
            currentDx*sum(abs( ...
                uCurrentMUSCL-exactCurrent));
    end
end

%% Órdenes observados

for meshIndex = 2:numberOfMeshes

    ordersGodunov(meshIndex) = ...
        log( ...
            errorsGodunov(meshIndex-1) ...
            / errorsGodunov(meshIndex)) ...
        / log(2);

    for limiterIndex = 1:numberOfLimiters

        ordersMUSCL(meshIndex,limiterIndex) = ...
            log( ...
                errorsMUSCL(meshIndex-1,limiterIndex) ...
                / errorsMUSCL(meshIndex,limiterIndex)) ...
            / log(2);
    end
end

%% Tabla de convergencia

convergenceTable = table( ...
    Nvalues, ...
    dxValues, ...
    errorsGodunov, ...
    ordersGodunov, ...
    errorsMUSCL(:,1), ...
    ordersMUSCL(:,1), ...
    errorsMUSCL(:,2), ...
    ordersMUSCL(:,2), ...
    errorsMUSCL(:,3), ...
    ordersMUSCL(:,3), ...
    errorsMUSCL(:,4), ...
    ordersMUSCL(:,4), ...
    'VariableNames', { ...
        'N', ...
        'dx', ...
        'Error_Godunov', ...
        'Orden_Godunov', ...
        'Error_Minmod', ...
        'Orden_Minmod', ...
        'Error_VanLeer', ...
        'Orden_VanLeer', ...
        'Error_VanAlbada', ...
        'Orden_VanAlbada', ...
        'Error_Superbee', ...
        'Orden_Superbee'});

fprintf('\n====================================================\n');
fprintf('TABLA DE CONVERGENCIA EN NORMA L1\n');
fprintf('====================================================\n\n');

disp(convergenceTable);

%% Figura 4: gráfica de convergencia

figure;

loglog( ...
    dxValues, errorsGodunov, 'o--', ...
    'LineWidth', 1.5, ...
    'MarkerSize', 6, ...
    'DisplayName', 'Godunov');

hold on;

for limiterIndex = 1:numberOfLimiters

    loglog( ...
        dxValues, ...
        errorsMUSCL(:,limiterIndex), ...
        'o-', ...
        'LineWidth', 1.4, ...
        'MarkerSize', 6, ...
        'DisplayName', ...
        sprintf('MUSCL-%s', ...
        limiters(limiterIndex)));

end

% Rectas de referencia de primer y segundo orden

referenceFirstOrder = ...
    errorsGodunov(end) ...
    *(dxValues/dxValues(end));

referenceSecondOrder = ...
    errorsMUSCL(end,2) ...
    *(dxValues/dxValues(end)).^2;

loglog( ...
    dxValues, referenceFirstOrder, ':', ...
    'LineWidth', 1.4, ...
    'DisplayName', 'Referencia orden 1');

loglog( ...
    dxValues, referenceSecondOrder, ':', ...
    'LineWidth', 1.4, ...
    'DisplayName', 'Referencia orden 2');

grid on;
xlabel('\Deltax');
ylabel('Error L^1');
title('Estudio de convergencia');
legend('Location', 'eastoutside');